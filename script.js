function createNoiseBuffer(context, seconds = 2) {
  const buffer = context.createBuffer(1, context.sampleRate * seconds, context.sampleRate);
  const data = buffer.getChannelData(0);
  for (let i = 0; i < data.length; i += 1) {
    data[i] = Math.random() * 2 - 1;
  }
  return buffer;
}

function fadeParam(param, value, duration = 0.4) {
  if (!audioContext) return;
  const now = audioContext.currentTime;
  param.cancelScheduledValues(now);
  param.setTargetAtTime(value, now, duration);
}

function initAudio() {
  if (audioReady) {
    if (audioContext.state === "suspended") audioContext.resume();
    return;
  }

  const Context = window.AudioContext || window.webkitAudioContext;
  if (!Context) {
    soundButton.textContent = "静";
    soundButton.disabled = true;
    return;
  }

  audioContext = new Context();
  masterGain = audioContext.createGain();
  musicGain = audioContext.createGain();
  windGain = audioContext.createGain();
  typeGain = audioContext.createGain();
  pageGain = audioContext.createGain();

  masterGain.gain.value = soundOn ? 0.72 : 0;
  musicGain.gain.value = 0.16;
  windGain.gain.value = 0.055;
  typeGain.gain.value = 0.5;
  pageGain.gain.value = 0.62;

  musicGain.connect(masterGain);
  windGain.connect(masterGain);
  typeGain.connect(masterGain);
  pageGain.connect(masterGain);
  masterGain.connect(audioContext.destination);

  startMusic();
  startWind();
  audioReady = true;
  soundButton.classList.toggle("is-active", soundOn);
}

function startMusic() {
  const chord = [196, 246.94, 293.66, 369.99];
  chord.forEach((frequency, offset) => {
    const oscillator = audioContext.createOscillator();
    const gain = audioContext.createGain();
    const filter = audioContext.createBiquadFilter();
    oscillator.type = "sine";
    oscillator.frequency.value = frequency;
    gain.gain.value = 0.05 / (offset + 1);
    filter.type = "lowpass";
    filter.frequency.value = 900;
    oscillator.connect(filter);
    filter.connect(gain);
    gain.connect(musicGain);
    oscillator.start(audioContext.currentTime + offset * 0.08);
  });

  const lfo = audioContext.createOscillator();
  const lfoGain = audioContext.createGain();
  lfo.frequency.value = 0.035;
  lfoGain.gain.value = 0.06;
  lfo.connect(lfoGain);
  lfoGain.connect(musicGain.gain);
  lfo.start();
}

function startWind() {
  const noise = audioContext.createBufferSource();
  const filter = audioContext.createBiquadFilter();
  const sway = audioContext.createOscillator();
  const swayGain = audioContext.createGain();
  noise.buffer = createNoiseBuffer(audioContext, 3);
  noise.loop = true;
  filter.type = "bandpass";
  filter.frequency.value = 560;
  filter.Q.value = 0.7;
  sway.frequency.value = 0.09;
  swayGain.gain.value = 180;
  sway.connect(swayGain);
  swayGain.connect(filter.frequency);
  noise.connect(filter);
  filter.connect(windGain);
  noise.start();
  sway.start();
}

function playTypeSound() {
  if (!audioReady || !soundOn) return;
  typingSoundTick += 1;
  const now = audioContext.currentTime;
  const click = audioContext.createBufferSource();
  const clickFilter = audioContext.createBiquadFilter();
  const clickGain = audioContext.createGain();
  click.buffer = createNoiseBuffer(audioContext, 0.055);
  clickFilter.type = "highpass";
  clickFilter.frequency.value = 1300 + Math.random() * 450;
  clickFilter.Q.value = 1.8;
  clickGain.gain.setValueAtTime(0.0001, now);
  clickGain.gain.exponentialRampToValueAtTime(0.16, now + 0.003);
  clickGain.gain.exponentialRampToValueAtTime(0.0001, now + 0.05);
  click.connect(clickFilter);
  clickFilter.connect(clickGain);
  clickGain.connect(typeGain);
  click.start(now);
  click.stop(now + 0.055);

  const gain = audioContext.createGain();
  const oscillator = audioContext.createOscillator();
  oscillator.type = "square";
  oscillator.frequency.value = 760 + Math.random() * 110;
  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(0.045, now + 0.003);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.045);
  oscillator.connect(gain);
  gain.connect(typeGain);
  oscillator.start(now);
  oscillator.stop(now + 0.05);
}

function playPageSound() {
  if (!audioReady || !soundOn) return;
  const now = audioContext.currentTime;
  const paper = audioContext.createBufferSource();
  const paperFilter = audioContext.createBiquadFilter();
  const paperGain = audioContext.createGain();
  paper.buffer = createNoiseBuffer(audioContext, 0.3);
  paperFilter.type = "bandpass";
  paperFilter.frequency.setValueAtTime(850, now);
  paperFilter.frequency.exponentialRampToValueAtTime(3100, now + 0.2);
  paperFilter.Q.value = 1.1;
  paperGain.gain.setValueAtTime(0.0001, now);
  paperGain.gain.exponentialRampToValueAtTime(0.36, now + 0.014);
  paperGain.gain.exponentialRampToValueAtTime(0.08, now + 0.12);
  paperGain.gain.exponentialRampToValueAtTime(0.0001, now + 0.29);
  paper.connect(paperFilter);
  paperFilter.connect(paperGain);
  paperGain.connect(pageGain);
  paper.start(now);
  paper.stop(now + 0.3);

  const confirm = audioContext.createOscillator();
  const confirmGain = audioContext.createGain();
  confirm.type = "triangle";
  confirm.frequency.setValueAtTime(380, now);
  confirm.frequency.exponentialRampToValueAtTime(640, now + 0.075);
  confirmGain.gain.setValueAtTime(0.0001, now);
  confirmGain.gain.exponentialRampToValueAtTime(0.18, now + 0.01);
  confirmGain.gain.exponentialRampToValueAtTime(0.0001, now + 0.11);
  confirm.connect(confirmGain);
  confirmGain.connect(pageGain);
  confirm.start(now);
  confirm.stop(now + 0.09);
}

function setSound(enabled) {
  soundOn = enabled;
  soundButton.classList.toggle("is-active", soundOn);
  soundButton.textContent = soundOn ? "声" : "静";
  if (masterGain) fadeParam(masterGain.gain, soundOn ? 0.72 : 0, 0.22);
}

function setBackground(src) {
  const scene = scenes[index];
  const fit = scene.fit || "cover";
  const isInset = fit !== "cover";
  const size = fit === "portraitClose" ? "auto 125vh" : fit === "portrait" ? "auto 115vh" : fit === "portraitSmall" ? "auto 145vh" : fit === "framed" ? "auto 80vh" : "cover";
  const position = fit === "portraitClose" ? "center -3vh" : fit === "portrait" ? "center -2vh" : fit === "portraitSmall" ? "center -11vh" : fit === "framed" ? "center 2vh" : "center";
  const current = backdrops[activeBackdrop];
  if (current.dataset.bg === src && current.dataset.fit === fit) return;

  window.clearTimeout(backdropTimer);
  const nextIndex = activeBackdrop === 0 ? 1 : 0;
  const next = backdrops[nextIndex];

  dialogue.classList.add("is-soft-changing");
  next.className = "backdrop-layer is-entering";
  next.style.backgroundImage = `url("${src}")`;
  next.style.backgroundSize = size;
  next.style.backgroundPosition = position;
  next.dataset.bg = src;
  next.dataset.fit = fit;
  next.classList.toggle("is-inset", isInset);

  requestAnimationFrame(() => {
    current.classList.remove("is-visible");
    current.classList.add("is-leaving");
    next.classList.remove("is-entering");
    next.classList.add("is-visible");
  });

  activeBackdrop = nextIndex;
  backdropTimer = window.setTimeout(() => {
    current.className = "backdrop-layer";
    dialogue.classList.remove("is-soft-changing");
  }, 1180);
}

function typeLine(text) {
  window.clearInterval(typingTimer);
  typedText = text;
  line.textContent = "";
  isTyping = true;
  typingSoundTick = 0;
  let cursor = 0;

  typingTimer = window.setInterval(() => {
    cursor += 1;
    line.textContent = text.slice(0, cursor);
    playTypeSound();
    if (cursor >= text.length) {
      finishTyping();
    }
  }, 34);
}

function finishTyping() {
  window.clearInterval(typingTimer);
  line.textContent = typedText;
  isTyping = false;
  scheduleAuto();
}

function renderScene() {
  const scene = scenes[index];
  setBackground(scene.bg);
  speaker.textContent = scene.speaker;
  choices.innerHTML = "";
  hint.textContent = scene.choices ? "选择一句回应" : index === scenes.length - 1 ? "故事结束 · 点击回到开头" : "点击画面继续";
  typeLine(scene.text);

  if (scene.choices) {
    for (const choice of scene.choices) {
      const button = document.createElement("button");
      button.type = "button";
      button.textContent = choice.label;
      button.addEventListener("click", (event) => {
        event.stopPropagation();
        if (isTyping) finishTyping();
        playPageSound();
        historyStack.push(index);
        index = choice.next;
        renderScene();
      });
      choices.appendChild(button);
    }
  }
}

function advance() {
  window.clearTimeout(autoTimer);
  if (isTyping) {
    finishTyping();
    playPageSound();
    return;
  }

  const scene = scenes[index];
  if (scene.choices) return;

  historyStack.push(index);
  index = index >= scenes.length - 1 ? 0 : index + 1;
  playPageSound();
  renderScene();
}

function goBack() {
  window.clearTimeout(autoTimer);
  if (isTyping) finishTyping();
  const previous = historyStack.pop();
  if (previous === undefined) return;
  index = previous;
  playPageSound();
  renderScene();
}

function scheduleAuto() {
  window.clearTimeout(autoTimer);
  const scene = scenes[index];
  if (!autoPlay || scene.choices || index === scenes.length - 1) return;
  const punctuationPauses = (scene.text.match(/[，。？！：…]/g) || []).length * 180;
  const delay = Math.min(4700, Math.max(1400, scene.text.length * 42 + punctuationPauses));
  autoTimer = window.setTimeout(advance, delay);
}

function restart() {
  window.clearTimeout(autoTimer);
  historyStack = [];
  index = 0;
  playPageSound();
  renderScene();
}

startButton.addEventListener("click", () => {
  initAudio();
  titleScreen.hidden = true;
  hud.hidden = false;
  playPageSound();
  renderScene();
});

advanceArea.addEventListener("click", advance);
backButton.addEventListener("click", goBack);
soundButton.addEventListener("click", () => {
  initAudio();
  setSound(!soundOn);
});
restartButton.addEventListener("click", restart);
autoButton.addEventListener("click", () => {
  autoPlay = !autoPlay;
  autoButton.classList.toggle("is-active", autoPlay);
  autoButton.textContent = autoPlay ? "Auto On" : "Auto";
  scheduleAuto();
});

window.addEventListener("keydown", (event) => {
  if (event.key === " " || event.key === "Enter") {
    event.preventDefault();
    if (!titleScreen.hidden) {
      startButton.click();
    } else {
      advance();
    }
  }
  if (event.key === "ArrowLeft") goBack();
});
